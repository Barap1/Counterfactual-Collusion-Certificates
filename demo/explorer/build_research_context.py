#!/usr/bin/env python3
"""Extract compact review context from frozen results, without changing the pack."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SOURCE = ROOT / "docs/enh/r2/run_par/RESULTS.json"


def build():
    raw = SOURCE.read_bytes()
    source = json.loads(raw)
    utility = {}
    for version, table in (("v1", "T8"), ("v0", "T8_v0")):
        rows = [r for r in source["tables"][table] if r["epsilon"] == 0]
        utility[version] = {
            "passed": sum(bool(r["pass_criterion"]) for r in rows),
            "total": len(rows),
            "undefined_gaps": sum(r["absolute_gap"] is None for r in rows),
        }
    return {
        "source": str(SOURCE.relative_to(ROOT)),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "criteria": {k: v["status"] for k, v in source["rq"].items()},
        "utility": utility,
        "rq3": source["rq"]["RQ3"]["by_epsilon"]["0"],
        "baseline": [r for r in source["tables"]["T5"] if r["epsilon"] == 0 and r["kind"] in ("P2", "P3")],
    }


if __name__ == "__main__":
    payload = json.dumps(build(), ensure_ascii=True, separators=(",", ":")).replace("</", "<\\/")
    (HERE / "research-context.js").write_text("/* Generated by build_research_context.py; source records unchanged. */\nwindow.CCC_DATA.review = " + payload + ";\n", encoding="ascii")
